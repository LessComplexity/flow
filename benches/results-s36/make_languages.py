#!/usr/bin/env python3
"""Build LANGUAGES.md from lang_mac.log / lang_i9.log.

Statistic follows the house rule: **min for single-threaded legs, median for
parallel legs** — a parallel minimum is the lucky-scheduling tail, a parallel
median is what the shape actually delivers. Both are in the raw logs.

Regenerate: python3 benches/results-s36/make_languages.py
"""
import re
from pathlib import Path

HERE = Path(__file__).parent
ROW = re.compile(r"^(\S+)\s+(\S+)\s+([\d.]+|n/a)\s+([\d.]+|n/a)\s*$")

SERIAL = ["mapal-1t", "cpp-1t", "rust-1t", "numpy", "numpy-1t"]
PAR = ["mapal-par", "cpp-mt", "rust-mt", "numpy-mt"]


def load(path):
    cells = {}
    for line in Path(path).read_text().splitlines():
        m = ROW.match(line)
        if not m or m.group(1) in ("shape", "----------"):
            continue
        shape, leg = m.group(1), m.group(2)
        try:
            cells.setdefault(shape, {})[leg] = (float(m.group(3)), float(m.group(4)))
        except ValueError:
            pass
    return cells


def pick(cell, leg, parallel):
    """min for serial legs, median for parallel legs."""
    if leg not in cell:
        return None
    return cell[leg][1] if parallel else cell[leg][0]


def fmt(v):
    return "—" if v is None else (f"{v:,.4f}" if v < 100 else f"{v:,.1f}")


ORDER = ["saxpy", "reduce", "transpose", "gather", "fir", "conv2d", "matmul1024"]
CLASS = {
    "saxpy": "streaming",
    "reduce": "reduction",
    "transpose": "data movement",
    "gather": "irregular reads",
    "fir": "compute (tiled)",
    "conv2d": "compute (tiled)",
    "matmul1024": "compute (tiled)",
}

out = ["# S36 per-language comparison — post-fix, both machines",
       "",
       "Generated by `make_languages.py` from `lang_mac.log` and `lang_i9.log`.",
       "Every leg is compute-only and self-timed, built from the same sources the",
       "published harnesses use, and run in one session on one machine.",
       "",
       "**Statistic: min for single-threaded legs, median for parallel legs.** A parallel",
       "minimum is the lucky-scheduling tail; the median is what the shape delivers. Both",
       "are in the raw logs. These are the first tables measured after the S36 clock-read",
       "fix, so the parallel columns are honest for the first time — see `BEFORE-AFTER.md`.",
       "",
       "All times in milliseconds. **Bold** marks the winner in each row's class.",
       ""]

for title, path, note in [
    ("Apple M4 Pro (10 P + 4 E), unpinned", "lang_mac.log",
     "clang 22.1.8 · rustc 1.95 · numpy 2.4.6 on Accelerate"),
    ("Intel i9-14900F, pinned to the 8 P-cores", "lang_i9.log",
     "gcc 16.1.1 · rustc 1.90 · numpy 2.3.5 on scipy-openblas · every leg under "
     "`taskset -c 0-15`, so all four languages see identical hardware"),
]:
    cells = load(HERE / path)
    out += [f"## {title}", "", note, "",
            "### Single-threaded", "",
            "| shape | class | Mapal | C++ | Rust | NumPy | Mapal vs best |",
            "| --- | --- | ---: | ---: | ---: | ---: | ---: |"]
    for shape in ORDER:
        c = cells.get(shape)
        if not c:
            continue
        m = pick(c, "mapal-1t", False)
        cpp = pick(c, "cpp-1t", False)
        rs = pick(c, "rust-1t", False)
        np_ = pick(c, "numpy-1t", False) or pick(c, "numpy", False)
        others = [v for v in (cpp, rs, np_) if v]
        best = min(others) if others else None
        ratio = f"**{best/m:.2f}× faster**" if best and m and m < best else (
            f"{m/best:.2f}× slower" if best and m else "—")
        cells_txt = []
        for v in (m, cpp, rs, np_):
            s = fmt(v)
            if v is not None and v == min([x for x in (m, cpp, rs, np_) if x is not None]):
                s = f"**{s}**"
            cells_txt.append(s)
        out.append(f"| `{shape}` | {CLASS[shape]} | " + " | ".join(cells_txt) + f" | {ratio} |")
    out += ["", "### Parallel", "",
            "| shape | class | Mapal | C++ | Rust | NumPy | Mapal vs best |",
            "| --- | --- | ---: | ---: | ---: | ---: | ---: |"]
    for shape in ORDER:
        c = cells.get(shape)
        if not c:
            continue
        m = pick(c, "mapal-par", True)
        cpp = pick(c, "cpp-mt", True)
        rs = pick(c, "rust-mt", True)
        np_ = pick(c, "numpy-mt", True) or pick(c, "numpy", False)
        others = [v for v in (cpp, rs, np_) if v]
        best = min(others) if others else None
        ratio = f"**{best/m:.2f}× faster**" if best and m and m < best else (
            f"{m/best:.2f}× slower" if best and m else "—")
        cells_txt = []
        for v in (m, cpp, rs, np_):
            s = fmt(v)
            if v is not None and v == min([x for x in (m, cpp, rs, np_) if x is not None]):
                s = f"**{s}**"
            cells_txt.append(s)
        out.append(f"| `{shape}` | {CLASS[shape]} | " + " | ".join(cells_txt) + f" | {ratio} |")
    out += [""]

# The FMA face: the same shapes emitted with --contract (single-rounding FMA), which is
# what every baseline already gets from -ffp-contract=fast / BLAS.
FMA = {}
for tag, path in (("mac", "lang_mac_fma.log"), ("i9", "lang_i9_fma.log")):
    if (HERE / path).exists():
        FMA[tag] = load(HERE / path)
if FMA:
    out += ["## The FMA face — the fair comparison",
            "",
            "Every table above is Mapal's **conformance** face: `EmitOpts::contract` defaults off,",
            "the ladder harness never passes `--contract`, and the emitted object contains **zero**",
            "FMA instructions (verified: `objdump -d matmul1024_f32.o | grep -c vfmadd` = 0). Every",
            "baseline meanwhile gets FMA for free — C++/Rust via `-ffp-contract=fast`, NumPy via BLAS.",
            "So the tables above compare Mapal's bit-exact face against everyone else's fused one.",
            "",
            "Re-emitted with `--contract` (28 `vfmadd` in the same object), same protocol:",
            "",
            "| machine | shape | conformance | **FMA** | best baseline | FMA gap |",
            "| --- | --- | ---: | ---: | ---: | ---: |"]
    BASE = {("mac", "matmul1024"): ("NumPy/Accelerate", 0.6869), ("i9", "matmul1024"): ("NumPy/OpenBLAS", 1.7411),
            ("mac", "fir"): ("C++ mt", 0.2041), ("i9", "fir"): ("C++ mt", 0.2373),
            ("mac", "conv2d"): ("C++ mt", 0.1300), ("i9", "conv2d"): ("Rust mt", 0.1578)}
    conf_logs = {"mac": load(HERE / "lang_mac.log"), "i9": load(HERE / "lang_i9.log")}
    for tag in ("mac", "i9"):
        for shape in ("matmul1024", "fir", "conv2d"):
            if tag not in FMA or shape not in FMA[tag]:
                continue
            conf = pick(conf_logs[tag].get(shape, {}), "mapal-par", True)
            fma = pick(FMA[tag][shape], "mapal-par", True)
            name, base = BASE[(tag, shape)]
            gap = f"**{base/fma:.2f}x faster**" if fma < base else f"{fma/base:.2f}x slower"
            out.append(f"| {tag} | `{shape}` | {fmt(conf)} | **{fmt(fma)}** | {fmt(base)} ({name}) | {gap} |")
    out += ["",
            "**On identical hardware with both sides fused, the OpenBLAS gap is 1.23x, not 1.85x.**",
            "On the Mac, Accelerate keeps a 3.3x lead because it reaches the AMX matrix unit, which is",
            "hardware Mapal does not target — that column is not a compiler comparison.",
            ""]

out += [
    "## Two rows that are NOT performance gaps",
    "",
    "**`reduce` parallel is a semantics comparison, not a speed one.** Mapal's fold is a",
    "strict left fold and stays on one lane; Rust's `run_reduce` splits into",
    "`thread_width()` chunks and folds the partials, and NumPy's `np.sum` is pairwise —",
    "**both compute a different function**, and Rust's answer even depends on the machine's",
    "thread count. At one thread, where all three compute the same left fold, **Mapal is the",
    "fastest of the three** on the i9: 0.3668 vs C++ 0.3821 vs Rust 0.3821. Reassociating a",
    "float sum is a permission the language has not granted (ADR-0032 D1's precision",
    "lattice, unimplemented) and a tree shape it has not pinned (ADR-0028, accepted, never",
    "built) — not an optimisation it failed to find.",
    "",
    "**The i9's sub-5 ms cells are frequency, not work.** That box runs `powersave` with",
    "`intel_pstate`. Measured with `perf` on the reduce kernel: the timed window costs a",
    "constant **2.1 M core cycles** in every configuration, while wall time ranges 0.38–2.01",
    "ms purely with the boost clock — at a *fixed* thread count, widening the affinity mask",
    "alone walks the median from 0.397 ms (2 CPUs) to 2.006 ms (16 CPUs), because a pool",
    "spread over more idle cores keeps them all at the ~1.07 GHz floor. Read the i9's small",
    "cells as cycles or not at all; the Mac column is the honest wall-clock one.",
    "",
    "## Reading it",
    "",
    "**NumPy is not one baseline.** On `matmul` and `reduce` it is a BLAS/vectorised",
    "library call — a different category of thing from a hand-written loop, and the",
    "number to beat. On `gather` and `transpose` it is NumPy doing the same work with",
    "Python-side overhead, and beating it there means little.",
    "",
    "**The C++/Rust matmul legs are naive triple loops**, not blocked kernels. Mapal",
    "beating them by 27–142× is a statement about tiling versus not tiling, not about",
    "Mapal versus C++. The honest matmul comparison is the NumPy row.",
    "",
    "**The split is the S35 finding, now quantified on two architectures.** Mapal wins",
    "the tiled compute shapes (`fir`, `conv2d`) on both machines, at one thread and in",
    "parallel. It loses the non-tiled shapes — `saxpy`, `reduce`, `gather` — because a",
    "plain `map` is not a tile site and emits a scalar loop, which is exactly the open",
    "P1 in `docs/next-session.md`.",
]

Path(HERE / "LANGUAGES.md").write_text("\n".join(out) + "\n")
print("wrote", HERE / "LANGUAGES.md")
