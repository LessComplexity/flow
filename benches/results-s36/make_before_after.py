#!/usr/bin/env python3
"""Build BEFORE-AFTER.md from the raw S36b logs in this directory.

One row per shape per configuration, pre beside post, so the A/B is readable
without cross-referencing five files. Regenerate with:

    python3 benches/results-s36/make_before_after.py
"""
import re
from pathlib import Path

HERE = Path(__file__).parent
ROW = re.compile(
    r"(\S+)\s+(\S+)\s+min=\s*([\d.]+)\s+median=\s*([\d.]+)\s+max=\s*([\d.]+)"
    r"(?:\s+min/med=\s*[\d.]+)?\s+n=\s*(\d+)\s+sub0\.01=(\d+)"
)
BASELINE_LEGS = ("cpp-1t", "cpp-mt", "numpy", "numpy-1t")


def load(path, section=None):
    """Parse one log. `section` picks a run out of a multi-run file."""
    text = Path(path).read_text()
    if section:
        marks = [m.start() for m in re.finditer(r"^== ", text, re.M)]
        for i, start in enumerate(marks):
            end = marks[i + 1] if i + 1 < len(marks) else len(text)
            chunk = text[start:end]
            if section in chunk.splitlines()[0]:
                text = chunk
                break
    cells = {}
    for line in text.splitlines():
        m = ROW.match(line.strip())
        if not m or m.group(2) in BASELINE_LEGS:
            continue
        shape, leg = m.group(1), m.group(2)
        cells.setdefault(shape, {})[leg] = dict(
            min=float(m.group(3)), med=float(m.group(4)),
            max=float(m.group(5)), n=int(m.group(6)), race=int(m.group(7)),
        )
    return cells


CONFIGS = [
    ("Apple M4 Pro — 10 P + 4 E, unpinned", 14,
     ("mac_pre.log", None), ("mac_post.log", None), "mapal-1t", "mapal-par"),
    ("Intel i9-14900F — 32 threads, unpinned", 32,
     ("box_pre.log", None), ("box_post.log", None), "mapal-1t", "mapal-par"),
    ("Intel i9-14900F — pinned to the 8 P-cores", 16,
     ("box_pinned.log", "(pre"), ("box_pinned.log", "(post"), "1t@P-core", "par@8P"),
]

out = ["# S36 before / after — the clock-read barrier",
       "",
       "Generated by `make_before_after.py` from the raw logs in this directory. Every",
       "cell is n = 100 runs. **before** = compiler at `35fb681` (clock read on the host",
       "spine); **after** = compiler at `896fb3c` (clock read as a task in the graph).",
       "Nothing else differs: same runtime, same flags, same machine, same session.",
       "",
       "`apparent` is the speedup the parallel *minimum* implies against the",
       "single-threaded *median*. It cannot honestly exceed the machine's thread count —",
       "when it does, the timer is reporting an interval the work already left.",
       "",
       "All times in milliseconds. `race` counts readings under 0.01 ms.",
       "",
       "**Read the pinned i9 table, not the unpinned one, for anything but the race",
       "counts.** That machine runs the `powersave` governor and cannot be changed without",
       "root, so its unpinned medians carry a frequency ramp — visible as ±20–34% swings on",
       "the *single-threaded* leg, which has no worker threads and therefore cannot race.",
       "Pinning collapses that to under 1.5%. The `median Δ` column is only meaningful",
       "where the 1-thread rows are stable.",
       "",
       "**A parallel median that rises after the fix is the correction, not a regression.**",
       "Work that used to start before the opening clock read now sits inside the measured",
       "interval. Total program wall time is unchanged (fir: 2.73 → 2.62 ms, n = 25).",
       ""]

for title, threads, (pre_f, pre_s), (post_f, post_s), leg1, legp in CONFIGS:
    pre = load(HERE / pre_f, pre_s)
    post = load(HERE / post_f, post_s)
    out += [f"## {title}", "",
            f"Thread ceiling **{threads}×**. before: `{pre_f}`"
            + (f" section `{pre_s}`" if pre_s else "")
            + f" · after: `{post_f}`" + (f" section `{post_s}`" if post_s else ""),
            "",
            "| shape | leg | before min | before median | after min | after median | median Δ |",
            "| --- | --- | ---: | ---: | ---: | ---: | ---: |"]
    for shape in sorted(pre):
        if shape not in post:
            continue
        for leg, label in ((leg1, "1 thread"), (legp, "parallel")):
            a, b = pre[shape].get(leg), post[shape].get(leg)
            if not a or not b:
                continue
            delta = (b["med"] - a["med"]) / a["med"] * 100
            out.append(f"| `{shape}` | {label} | {a['min']:.4f} | {a['med']:.4f} "
                       f"| {b['min']:.4f} | {b['med']:.4f} | {delta:+.1f}% |")
    out += ["",
            "| shape | apparent before | apparent after | race before | race after | verdict |",
            "| --- | ---: | ---: | ---: | ---: | --- |"]
    bad_pre = bad_post = 0
    for shape in sorted(pre):
        if shape not in post:
            continue
        a1, ap = pre[shape][leg1], pre[shape][legp]
        b1, bp = post[shape][leg1], post[shape][legp]
        sa, sb = a1["med"] / ap["min"], b1["med"] / bp["min"]
        bad_a, bad_b = sa > threads * 1.15, sb > threads * 1.15
        bad_pre += bad_a
        bad_post += bad_b
        verdict = ("**impossible → ok**" if bad_a and not bad_b
                   else "ok → ok (control)" if not bad_a and not bad_b
                   else "**REGRESSED**")
        out.append(f"| `{shape}` | {sa:,.1f}× | {sb:,.1f}× | {ap['race']} | {bp['race']} "
                   f"| {verdict} |")
    out += ["", f"**{bad_pre} of 7 shapes impossible before, {bad_post} of 7 after.**", ""]

Path(HERE / "BEFORE-AFTER.md").write_text("\n".join(out))
print("wrote", HERE / "BEFORE-AFTER.md")
